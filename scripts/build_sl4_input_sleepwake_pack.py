#!/usr/bin/env python3
"""Build the deterministic, public SL4 input + lid/SAM wake driver archive."""
from pathlib import Path
import argparse, hashlib, json, zipfile, plistlib, subprocess, struct

NAMES=("VoodooGPIO","VoodooSerial","VoodooInput","BigSurface","BigSurfaceHIDDriver")
EXPECTED_EXE_SHA={
 "VoodooGPIO":"882dcc1fe9a44de10ae6a55a194e2acd6f683ffd3518cbfef8803a84b6e915f8",
 "VoodooSerial":"b3b8b051a95f8ebc02eff7856da2e41d0d76fe8285dd14d8477e35abdfefdb9e",
 "VoodooInput":"a5d1385dad0aa25b4e5da76d3160bdcab6b57b52da72e108e9e8d031d1bf408c",
 "BigSurface":"61a9aeff603f57178ff3588ee16653c94416c10a51814bcc62f26919261131c7",
 "BigSurfaceHIDDriver":"a2f62c00592707ae81ecbb18d4c40f0dc812528da57ae98445ecbba7af93199a",
}
AML_SHA="96efe9f179bbf62b9d30c2742f6d5be303d0c78b5f569b31c562e0035903aefb"
PACKAGE="SL4-TGL-Input-SleepWake-v2-beta.zip"

def digest(data): return hashlib.sha256(data).hexdigest()

def normalized_macho_digest(data):
    # LC_UUID is generated by ld and changes between equivalent builds.
    # Zero only the UUID bytes; all executable code and other load commands remain pinned.
    blob=bytearray(data)
    if blob[:4] not in (b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf"):
        raise RuntimeError("Not a 64-bit Mach-O executable")
    ncmds=struct.unpack_from("<I",blob,16)[0]
    offset=32
    for _ in range(ncmds):
        command,size=struct.unpack_from("<II",blob,offset)
        if size<8 or offset+size>len(blob):
            raise RuntimeError("Malformed Mach-O load command")
        if command==0x1B:
            if size<24: raise RuntimeError("Malformed LC_UUID")
            blob[offset+8:offset+24]=bytes(16)
            return digest(blob)
        offset+=size
    raise RuntimeError("Mach-O LC_UUID missing")

def assemble(source, licenses, aml, dsl, out):
    if out.exists(): raise RuntimeError("Refusing overwrite: "+str(out))
    content={}
    versions={}
    normalized_exes={}
    for name in NAMES:
        bundle=source/(name+".kext")
        info_path=bundle/"Contents/Info.plist"
        exe=bundle/"Contents/MacOS"/name
        if not info_path.is_file() or not exe.is_file(): raise RuntimeError("Incomplete kext: "+name)
        info=plistlib.loads(info_path.read_bytes())
        versions[name]=info.get("CFBundleVersion")
        if normalized_macho_digest(exe.read_bytes())!=EXPECTED_EXE_SHA[name]:
            raise RuntimeError("Unrecognized built executable code: "+name)
        if name=="VoodooGPIO" and versions[name]!="1.2.5": raise RuntimeError("Wrong VoodooGPIO version")
        if name=="BigSurface" and versions[name]!="1.2.1": raise RuntimeError("Wrong BigSurface version")
        if name=="BigSurface" and info["IOKitPersonalities"]["Surface Serial Hub"].get("SL4SAMWakeEnabled") is not True:
            raise RuntimeError("SAM wake personality not enabled")
        executable=exe.read_bytes()
        normalized_exes[name]=normalized_macho_digest(executable)
        content["Kexts/"+name+".kext/Contents/Info.plist"]=info_path.read_bytes()
        content["Kexts/"+name+".kext/Contents/MacOS/"+name]=executable
    gpio_binary=content["Kexts/VoodooGPIO.kext/Contents/MacOS/VoodooGPIO"]
    strings=subprocess.check_output(["/usr/bin/strings","-"],input=gpio_binary)
    forbidden=(b"SL4LidGPIOProbe",b"SL4LidGPEArmStatus",b"SL4LidGPERecoveryCount",
               b"SL4LidResume",b"SL4SAMWakeArmed",b"SL4SAMWakeGPIO",
               b"Armed SAM wake",b"Disarmed SAM wake",b"SAM GPIO wake")
    leftovers=[x.decode() for x in forbidden if x in strings]
    if leftovers: raise RuntimeError("Temporary diagnostics remain: "+", ".join(leftovers))
    aml_raw=aml.read_bytes()
    if len(aml_raw)!=100 or sum(aml_raw)%256 or digest(aml_raw)!=AML_SHA:
        raise RuntimeError("SSDT-SL4-LIDWAKE.aml checksum or source identity mismatch")
    content["ACPI/SSDT-SL4-LIDWAKE.aml"]=aml_raw
    content["ACPI/SSDT-SL4-LIDWAKE.dsl"]=dsl.read_bytes()
    notices={
      "BigSurface-GPL3.txt":licenses/"LICENSE.txt",
      "VoodooGPIO-GPL3.md":licenses/"Dependencies/VoodooGPIO/LICENSE.md",
      "VoodooSerial-GPL3.txt":licenses/"Dependencies/VoodooSerial/LICENSE.txt",
      "BigSurfaceHIDDriver-GPL3.txt":licenses/"Dependencies/BigSurfaceHIDDriver/LICENSE",
    }
    for name,path in notices.items():
        if not path.is_file() or path.stat().st_size<500: raise RuntimeError("Missing GPL notice: "+str(path))
        content["LICENSES/"+name]=path.read_bytes()
    content["SOURCE.txt"]=(
      "Surface Laptop 4 Intel i7-1185G7 / Tiger Lake-LP input + sleep/wake profile.\n"
      "Reproducible build: experiments/sl4-input/build-bigsurface-sl4-sleepwake.py\n"
      "Production patch: experiments/sl4-input/patches/sl4-sleepwake-production.patch\n"
      "BigSurface upstream: https://github.com/Xiashangning/BigSurface @ 82826312a429ede6e6f8441d49de2e2096b69ae4\n"
      "VoodooGPIO pin tables: https://github.com/VoodooI2C/VoodooGPIO @ d415406ecf25b5e322d3db9a4abab5719106fac1\n"
      "Lilu 1.7.2; VirtualSMC 1.3.8. GPL-3.0-or-later notices are in LICENSES/.\n"
      "Includes guarded F11/GPP_F11 lid GPE recovery and SAM GPIO 0x12A wake arming.\n"
      "No diagnostic probe timer, diagnostic IORegistry properties, private EFI, SMBIOS or serial data.\n"
      "SAM keyboard/trackpad wake is included but still requires physical validation on target hardware.\n"
    ).encode()
    manifest={
      "format":2,
      "release":"SL4-TGL-Input-SleepWake-v2-beta",
      "hardware":"Surface Laptop 4 Intel i7-1185G7 / Tiger Lake-LP",
      "kext_versions":versions,
      "normalized_macho_sha256":normalized_exes,
      "kexts":list(NAMES),
      "acpi":["SSDT-SL4-LIDWAKE.aml"],
      "features":{
        "lid_wake_gpe":"F11/GPP_F11 guarded arm + minimal bounded runtime watchdog",
        "sam_keyboard_trackpad_wake":"GPIO 0x12A edge-rising wake arm enabled on Surface Serial Hub sleep transition",
        "diagnostic_probe_timer":False,
        "diagnostic_ioregistry_telemetry":False,
        "diagnostic_event_logs":False
      },
      "validation":{
        "lid_wake":"four consecutive physical clamshell sleep/wake cycles confirmed on the reference Surface with VoodooGPIO 1.2.4; 1.2.5 is a clean production rebuild pending its own physical regression",
        "sam_wake":"not physically confirmed; included as experimental"
      },
      "private_efi_included":False,
      "sha256":{key:digest(value) for key,value in sorted(content.items())}
    }
    content["MANIFEST.json"]=(json.dumps(manifest,indent=2,sort_keys=True)+"\n").encode()
    out.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(out,"x",compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for key,value in sorted(content.items()):
            info=zipfile.ZipInfo(key,(1980,1,1,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=(0o100644<<16)
            z.writestr(info,value)
    with zipfile.ZipFile(out) as z:
        if z.testzip() is not None: raise RuntimeError("ZIP integrity failure")
        if set(z.namelist())!=set(content): raise RuntimeError("ZIP member mismatch")
        for key,value in content.items():
            if digest(z.read(key))!=digest(value): raise RuntimeError("ZIP content mismatch: "+key)
    print(json.dumps({"asset":out.name,"bytes":out.stat().st_size,"sha256":digest(out.read_bytes()),
                      "files":len(content),"versions":versions},indent=2))

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--source",type=Path,required=True)
    p.add_argument("--license-root",type=Path,required=True)
    p.add_argument("--aml",type=Path,required=True)
    p.add_argument("--dsl",type=Path,required=True)
    p.add_argument("--out",type=Path,required=True)
    a=p.parse_args()
    assemble(a.source,a.license_root,a.aml,a.dsl,a.out)
if __name__=="__main__": main()
